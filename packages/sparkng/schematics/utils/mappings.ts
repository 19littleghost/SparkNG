import generatedVersions from './versions.json';

export const MODULE_MAP: ReadonlyMap<string, string> = new Map([
    ['primeng', '@bdspark/sparkng'],
    ['primeicons', '@bdspark/sparkng-icons'],
    ['@primeuix/themes', '@bdspark/sparkng-themes'],
    ['@primeuix/styled', '@bdspark/sparkng-styled'],
    ['@primeuix/styles', '@bdspark/sparkng-styles'],
    ['@primeuix/utils', '@bdspark/sparkng-utils'],
    ['@primeuix/motion', '@bdspark/sparkng-motion'],
    ['tailwindcss-primeui', '@bdspark/sparkng-tailwindcss'],
    ['primelocale', '@bdspark/sparkng-locale']
]);

// Files that were renamed inside a package, so the prefix mapping alone would produce a
// broken path. Checked before MODULE_MAP for module specifiers, and applied verbatim to
// stylesheets and angular.json/project.json (e.g. "node_modules/primeicons/primeicons.css").
export const SPECIFIER_RENAMES: ReadonlyMap<string, string> = new Map([['primeicons/primeicons.css', '@bdspark/sparkng-icons/icons.css']]);

export const IDENTIFIER_RENAMES: ReadonlyMap<string, string> = new Map([
    ['providePrimeNG', 'provideOptimus'],
    ['PrimeNG', 'Optimus'],
    ['PrimeNGConfigType', 'OptimusConfigType'],
    // The icon constants class was renamed alongside the primeicons -> @bdspark/sparkng-icons package.
    // @bdspark/sparkng/api keeps a deprecated PrimeIcons alias, so unmigrated code still
    // compiles, but rewriting to BdsparkIcons moves users onto the current API.
    ['PrimeIcons', 'BdsparkIcons']
]);

// versions.json is generated by scripts/build-schematics.mjs from the workspace package
// manifests (and the pnpm-workspace.yaml catalog for @bdspark/sparkng-icons) — never edit it by hand.
export const VERSIONS: Readonly<Record<string, string>> = generatedVersions;

// A stylesheet `@import`/`@plugin`/`url(...)` reference, or an entry in the styles array of
// angular.json/project.json, is a path rather than a module specifier — it may carry a webpack
// tilde or a node_modules/ prefix that has to survive the rename.
const PACKAGE_PREFIX_RE = /^(.*(?:node_modules\/|~))?(.*)$/;

export function mapAssetReference(reference: string): string | null {
    const match = PACKAGE_PREFIX_RE.exec(reference);
    const prefix = match?.[1] ?? '';
    const mapped = mapModuleSpecifier(match?.[2] ?? reference);
    return mapped === null ? null : `${prefix}${mapped}`;
}

export function mapModuleSpecifier(spec: string): string | null {
    const renamed = SPECIFIER_RENAMES.get(spec);
    if (renamed !== undefined) {
        return renamed;
    }
    for (const [from, to] of MODULE_MAP) {
        if (spec === from) {
            return to;
        }
        if (spec.startsWith(from + '/')) {
            return to + spec.slice(from.length);
        }
    }
    return null;
}
